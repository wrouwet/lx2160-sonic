#!/usr/bin/env python3
"""Generate firmware/dpl/dpl-lx2160ardb-sonic.dts from NXP's dpl-eth.19.dts.

NXP's layout creates two DPNIs: dpni@0 -> dpmac@17 (RGMII 1G) and
dpni@1 -> dpmac@2 (40G QSFP). Keep those and add DPNIs for the other copper
ports: dpmac@18 (RGMII 1G) and dpmac@3/@4 (AQR107 10GBASE-T). The DPAA2
Ethernet driver takes one DPBP per DPNI and up to one DPCON per CPU per DPNI,
so scale those to 6 and 80 (5 DPNIs x 16 cores).
"""
import pathlib
import re
import sys

W = pathlib.Path(__file__).resolve().parent.parent
SRC = W / 'src/mc-utils/config/lx2160a/LX2160A-RDB/dpl-eth.19.dts'
DST = W / 'firmware/dpl/dpl-lx2160ardb-sonic.dts'

NEW_LINKS = [(2, 18), (3, 3), (4, 4)]   # (dpni, dpmac)
NUM_DPNI = 5
NUM_DPBP = 6
NUM_DPCON = 80

HEADER = """/*
 * LX2160ARDB DPL for SONiC (SerDes 19_5_2), derived from NXP mc-utils
 * dpl-eth.19.dts (lf-6.18.37-2.1.0). Changes:
 *   - dpni@2..4 added for dpmac@18 (RGMII 1G) and dpmac@3/@4 (AQR107 10GBASE-T);
 *     dpni@0 -> dpmac@17 and dpni@1 -> dpmac@2 are unchanged.
 *   - dpbp 0..5 (one buffer pool per DPNI) and dpcon 0..79 (up to 16 channels
 *     per DPNI on 16 cores), so every interface gets its full set.
 * Generated by scripts/mk-dpl.py; edit that, not this file.
 */
"""


def ids(n):
    return '<' + ' '.join(hex(i) for i in range(n)) + '>'


def replace_once(s, old, new):
    if s.count(old) != 1:
        sys.exit(f'mk-dpl: expected exactly one match for {old!r}')
    return s.replace(old, new)


def main():
    s = SRC.read_text()

    for typ, n in (('dpni', NUM_DPNI), ('dpbp', NUM_DPBP), ('dpcon', NUM_DPCON)):
        s, k = re.subn(rf'(type = "{typ}";\s*ids = )<[^>]*>', rf'\g<1>{ids(n)}', s)
        if k != 1:
            sys.exit(f'mk-dpl: no obj_set for {typ}')

    dpni = '\t\tdpni@%d {\n\t\t\toptions = "";\n\t\t\tnum_queues = <0x10>;\n\t\t\tnum_tcs = <0x1>;\n\t\t};\n'
    s = replace_once(s, '\t\tdpmac@2 {',
                     ''.join(dpni % i for i, _ in NEW_LINKS) + '\t\tdpmac@2 {')

    last_dpbp = '\t\tdpbp@1 {\n\t\t};\n'
    s = replace_once(s, last_dpbp,
                     last_dpbp + ''.join('\t\tdpbp@%d {\n\t\t};\n' % i for i in range(2, NUM_DPBP)))

    dpcon = '\t\tdpcon@%d {\n\t\t\tnum_priorities = <0x2>;\n\t\t};\n'
    s = replace_once(s, dpcon % 31, ''.join(dpcon % i for i in range(31, NUM_DPCON)))

    conn = '\t\tconnection@%d {\n\t\t\tendpoint1 = "dpni@%d";\n\t\t\tendpoint2 = "dpmac@%d";\n\t\t};\n'
    last_conn = conn % (2, 1, 2)
    s = replace_once(s, last_conn,
                     last_conn + ''.join(conn % (3 + k, ni, mac) for k, (ni, mac) in enumerate(NEW_LINKS)))

    s = replace_once(s, '/dts-v1/;', HEADER + '/dts-v1/;')
    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text(s)
    print(DST)


if __name__ == '__main__':
    main()
